/**
 * Triggers a browser download of the generated Q-SYS CSS theme file.
 */
export function downloadQsysThemeCss(theme: ThemeType): void {
  const cssString = generateQsysThemeCss(theme);
  const blob = new Blob([cssString], { type: 'text/css' });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = 'qsys-theme.css';
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}
